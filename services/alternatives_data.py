def get_site(slug: str) -> dict[str, Any] | None:
    """Retourne la configuration d'un site à partir de son slug."""
    return STREAMING_SITES.get(slug)


def get_all_sites() -> list[dict[str, Any]]:
    """Retourne la liste de tous les sites répertoriés triés alphabétiquement."""
    return sorted(STREAMING_SITES.values(), key=lambda s: s["name"].lower())


def get_sites_by_category(category: str) -> list[dict[str, Any]]:
    """Filtre les sites selon leur catégorie."""
    return [s for s in get_all_sites() if s["category"] == category]


